import random
slt = sorted(random.sample(range(0, 777), 101)) #создается сортированный список из случайного 101 числа
x =int(input("Введите число:")) #искомый элемент
k=-1 
c=0
print("Стартовый список:", slt)
print("Линейный поиск:")
for i in range(len(slt)): #цикл для перебора всех эл
  c+= 1
  if x==slt[i]:
    k=i
    break #заканчивается если элемент найден
if k!=-1: #если нашелся элемент
  print("Индекс элемента:", k)
  print("Количество сравнений: ", c) 
else: #если элемент не нашелся
  print("Числа нет")
  print("Количество сравнений:", c)
print("Бинарный поиск:")
a=0 
b=len(slt)-1 
k2=-1 
c2=0 
while a<=b: #цикл работает до того как левая граница перешагнет правую
  c2+=1
  m=(a+b)//2 
  if slt[m]==x: #если элемент в середние равен нужному
    k2=m
    break
  elif slt[m]<x: #если элемент в середине меньше нужного
    a=m+1 
  else: 
    b=m-1 
if k2==-1: #если элемент не найден
  print("Числа нет")
  print("Количество сравнений:", c2)
else: #если элемент найден
  print("Индекс элемента:", k2)
  print("Количество сравнений:", c2)